fn fnv64(s: &str) -> u64 {
    let mut h: u64 = 0xcbf29ce484222325;
    for &b in s.as_bytes() {
        h ^= b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    h
}

fn record_text(s: &str) -> serde_json::Value {
    if s.len() <= MAX_RECORDED {
        serde_json::Value::String(s.to_string())
    } else {
        serde_json::json!({ "len": s.len(), "fnv64": format!("{:016x}", fnv64(s)) })
    }
}

fn matches_record(actual: &str, rec: &serde_json::Value) -> bool {
    match rec {
        serde_json::Value::String(s) => s == actual,
        serde_json::Value::Object(o) => {
            o["len"].as_u64() == Some(actual.len() as u64)
                && o["fnv64"].as_str() == Some(format!("{:016x}", fnv64(actual)).as_str())
        }
        _ => false,
    }
}

fn record_of(p: &Program, out: &Outcome) -> serde_json::Value {
    let mut rec = serde_json::json!({
        "origin": p.origin,
        "exit": out.exit,
        "stdout": record_text(&out.stdout),
        "stderr": record_text(&out.stderr),
    });
    if !p.generated {
        match std::str::from_utf8(&p.src) {
            Ok(s) => rec["src"] = serde_json::Value::String(s.to_string()),
            Err(_) => rec["src_hex"] = serde_json::Value::String(hex(&p.src)),
        }
    }
    if !p.args.is_empty() {
        rec["args"] = serde_json::json!(p.args);
    }
    if !p.positional.is_empty() {
        rec["positional"] = serde_json::json!(p.positional);
    }
    if let Some(h) = &p.home {
        rec["home"] = serde_json::json!(h);
    }
    rec
}

fn first_difference(a: &str, b: &str) -> String {
    let al: Vec<&str> = a.lines().collect();
    let bl: Vec<&str> = b.lines().collect();
    for i in 0..al.len().max(bl.len()) {
        let x = al.get(i).copied().unwrap_or("<eof>");
        let y = bl.get(i).copied().unwrap_or("<eof>");
        if x != y {
            return format!("line {}: jq {:?} vs ours {:?}", i + 1, x, y);
        }
    }
    "(identical lines)".into()
}

/// Runs `f` on a thread with a big stack: the deepest programs nest as deeply as
/// jq's parser allows, and this test checks the output, not our stack usage.
fn on_big_stack<T: Send + 'static>(f: impl FnOnce() -> T + Send + 'static) -> T {
    std::thread::Builder::new()
        .stack_size(256 << 20)
        .spawn(f)
        .unwrap()
        .join()
        .unwrap()
}

#[test]
fn disasm_matches_recorded_jq() {
    on_big_stack(|| {
        let content = std::fs::read_to_string(data_dir().join("disasm.jsonl"))
            .expect("tests/jq_compile/disasm.jsonl");
        let generated: HashMap<String, Vec<u8>> = generated_programs().into_iter().collect();
        let mut failures = Vec::new();
        let mut timings = Vec::new();
        let mut n = 0;
        for line in content.lines() {
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let rec: serde_json::Value = serde_json::from_str(line).unwrap();
            let origin = rec["origin"].as_str().unwrap_or("").to_string();
            let p = match json_program(&rec, origin.clone()) {
                Some(p) => p,
                None => match generated.get(&origin) {
                    Some(src) => Program::new(origin.clone(), src.clone()),
                    None => panic!("recorded program {origin} is not generated any more"),
                },
            };
            n += 1;
            let t0 = std::time::Instant::now();
            let got = ours(&p);
            timings.push((t0.elapsed(), origin.clone()));
            let exit = rec["exit"].as_i64().unwrap() as i32;
            let ok = got.exit == exit
                && matches_record(&got.stdout, &rec["stdout"])
                && matches_record(&got.stderr, &rec["stderr"]);
            if !ok {
                let detail = match (&rec["stdout"], &rec["stderr"]) {
                    (serde_json::Value::String(o), serde_json::Value::String(e)) => {
                        first_difference(
                            &format!("{o}{e}"),
                            &format!("{}{}", got.stdout, got.stderr),
                        )
                    }
                    _ => "(recorded as a hash; run disasm_vs_live_jq)".into(),
                };
                failures.push(format!(
                    "{origin}: {:?}\n  exit: jq {exit} ours {}\n  {detail}",
                    show(&p.src, 120),
                    got.exit
                ));
            }
        }
        assert!(n > 3000, "only {n} recorded programs");
        if std::env::var("QJ_TIMING").is_ok() {
            timings.sort();
            let total: Duration = timings.iter().map(|t| t.0).sum();
            eprintln!("total {total:?}");
            for (t, o) in timings.iter().rev().take(25) {
                eprintln!("{t:?} {o}");
            }
        }
        if !failures.is_empty() {
            panic!(
                "{} of {} programs differ from jq:\n{}",
                failures.len(),
                n,
                failures
                    .iter()
                    .take(40)
                    .cloned()
                    .collect::<Vec<_>>()
                    .join("\n")
            );
        }
    });
}

/// jq compiles every program at its parser's nesting limits; so must we, on a thread
/// with the default 2 MiB stack (nothing in the compiler recurses over the nesting).
/// Unoptimized builds get 16 MiB: the AST's derived `Drop` for nested destructuring
/// patterns (`. as [[[...]]]`) recurses, with big debug frames.
#[test]
fn deepest_programs_compile_on_a_small_stack() {
    let stack = if cfg!(debug_assertions) {
        16 << 20
    } else {
        2 << 20
    };
    for (origin, src) in deepest_programs() {
        let ok = std::thread::Builder::new()
            .stack_size(stack)
            .spawn(move || {
                let opts = options(&Program::new(String::new(), Vec::new()));
                jq_compile_args(&src, &opts).is_ok()
            })
            .unwrap()
            .join()
            .unwrap();
        assert!(ok, "{origin} doesn't compile");
    }
}

