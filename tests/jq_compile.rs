//! jq 1.8.1 compiler conformance for `qj::jq::lang` (Track C1): bytecode and
//! compile errors, compared with `jq --debug-dump-disasm`.
//!
//! * `disasm_matches_recorded_jq`: fast. Replays `tests/jq_compile/disasm.jsonl`,
//!   which records what jq 1.8.1 prints for `jq --debug-dump-disasm -L modules --
//!   PROGRAM </dev/null` (the disassembly, or the compile errors and exit code 3) for
//!   every program of the upstream `.test` files (including `%%FAIL` blocks), qj's
//!   corpus (`tests/jq_compat/corpus/*.test`), Track P's corpus (`tests/jq_lang/`),
//!   this track's corpus (`tests/jq_compile/corpus.jsonl`: binding and scoping edge
//!   cases, named arguments, `$ENV`, modules), and generated deep programs. Our
//!   compiler must print exactly the same.
//! * `disasm_vs_live_jq` (ignored): the same against the jq binary; `QJ_BLESS=1`
//!   rewrites `disasm.jsonl`, `QJ_FILTER=text` selects programs.
//! * `adhoc` (ignored): `QJ_PROGRAM='...'` shows ours and jq's output.
//!
//!   ```text
//!   cargo test --release --test jq_compile -- --ignored --nocapture
//!   QJ_BLESS=1 cargo test --release --test jq_compile disasm_vs_live_jq -- --ignored --nocapture
//!   QJ_PROGRAM='def f: .; f' cargo test --release --test jq_compile adhoc -- --ignored --nocapture
//!   ```
//!
//! jq runs in `tests/jq_compat` with a fixed environment (see [`ENV`]) and
//! `-L modules`; paths under `tests/jq_compat` are recorded as `$ROOT`. Outputs
//! longer than [`MAX_RECORDED`] bytes are recorded as a hash.

use std::collections::{HashMap, HashSet};
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::Duration;

use qj::jq::lang::bytecode::dump_disassembly;
use qj::jq::lang::linker::{JqAttrs, dirname, jq_realpath};
use qj::jq::lang::{CompileOptions, jq_compile_args};
use qj::jq::value::{Object, Str, Value};

const ROOT: &str = env!("CARGO_MANIFEST_DIR");

/// The environment jq runs with (sorted, as `Command` passes it).
const ENV: &[(&str, &str)] = &[("HOME", "/nonexistent-qj-home"), ("QJ_TEST", "1")];

/// Outputs longer than this are recorded as a hash (plus their length).
const MAX_RECORDED: usize = 256;

fn compat_dir() -> PathBuf {
    Path::new(ROOT).join("tests/jq_compat")
}

fn data_dir() -> PathBuf {
    Path::new(ROOT).join("tests/jq_compile")
}

fn jq_binary() -> PathBuf {
    if let Ok(jq) = std::env::var("JQ") {
        return PathBuf::from(jq);
    }
    let mise = PathBuf::from(std::env::var("HOME").unwrap_or_default())
        .join(".local/share/mise/installs/jq/1.8.1/jq");
    if mise.exists() {
        return mise;
    }
    PathBuf::from("jq")
}

