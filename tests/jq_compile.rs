fn disasm_vs_live_jq_impl() {
    let jq = jq_binary();
    match Command::new(&jq).arg("--version").output() {
        Ok(o) if String::from_utf8_lossy(&o.stdout).trim() == "jq-1.8.1" => {}
        _ => {
            eprintln!("disasm_vs_live_jq: skipped, need jq 1.8.1 (set JQ)");
            return;
        }
    }
    let filter = std::env::var("QJ_FILTER").ok();
    let programs: Vec<Program> = collect_programs()
        .into_iter()
        .filter(|p| {
            filter.as_ref().is_none_or(|f| {
                String::from_utf8_lossy(&p.src).contains(f.as_str())
                    || p.origin.contains(f.as_str())
            })
        })
        .collect();

    // Run jq in parallel.
    let jobs = std::thread::available_parallelism().map_or(4, |n| n.get());
    let next = std::sync::atomic::AtomicUsize::new(0);
    let mut jq_results: Vec<Option<Outcome>> = vec![None; programs.len()];
    std::thread::scope(|s| {
        let handles: Vec<_> = (0..jobs)
            .map(|_| {
                s.spawn(|| {
                    let mut done = Vec::new();
                    loop {
                        let i = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                        if i >= programs.len() {
                            break;
                        }
                        done.push((i, live_jq(&jq, &programs[i])));
                    }
                    done
                })
            })
            .collect();
        for h in handles {
            for (i, r) in h.join().unwrap() {
                jq_results[i] = r;
            }
        }
    });

    let mut pass = 0;
    let mut crashed = Vec::new();
    let mut fails = Vec::new();
    let mut records = Vec::new();
    let (mut ok_disasm, mut tot_disasm, mut ok_err, mut tot_err) = (0, 0, 0, 0);
    for (p, jq_out) in programs.iter().zip(&jq_results) {
        let Some(jq_out) = jq_out else {
            crashed.push(p.origin.clone());
            continue;
        };
        let got = ours(p);
        let same = &got == jq_out;
        if jq_out.exit == 0 {
            tot_disasm += 1;
            ok_disasm += same as usize;
        } else {
            tot_err += 1;
            ok_err += same as usize;
        }
        if same {
            pass += 1;
        } else {
            fails.push((p, jq_out.clone(), got));
        }
        records.push(record_of(p, jq_out));
    }
    let report_path = Path::new(env!("CARGO_TARGET_TMPDIR")).join("jq_compile_report.txt");
    let mut report = std::fs::File::create(&report_path).unwrap();
    for (p, jq_out, got) in &fails {
        let _ = writeln!(
            report,
            "=== {} {:?} {:?} {:?}\n--- jq (exit {})\n{}{}--- ours (exit {})\n{}{}",
            p.origin,
            show(&p.src, 300),
            p.args,
            p.positional,
            jq_out.exit,
            jq_out.stdout,
            jq_out.stderr,
            got.exit,
            got.stdout,
            got.stderr
        );
    }
    eprintln!(
        "disasm_vs_live_jq: {pass}/{} identical; disassembly {ok_disasm}/{tot_disasm}, \
         compile errors {ok_err}/{tot_err}; {} skipped (jq crashed or timed out: {:?}); report: {}",
        programs.len() - crashed.len(),
        crashed.len(),
        crashed,
        report_path.display()
    );
    for (p, jq_out, got) in fails.iter().take(15) {
        eprintln!(
            "  {} {:?}: {}",
            p.origin,
            show(&p.src, 80),
            first_difference(
                &format!("{}{}", jq_out.stdout, jq_out.stderr),
                &format!("{}{}", got.stdout, got.stderr)
            )
        );
    }
    if std::env::var("QJ_BLESS").is_ok_and(|v| v == "1") && filter.is_none() {
        let path = data_dir().join("disasm.jsonl");
        let mut f = std::fs::File::create(&path).unwrap();
        writeln!(
            f,
            "# jq 1.8.1 --debug-dump-disasm -L modules [ARGS] -- PROGRAM </dev/null, run in tests/jq_compat.\n\
             # Generated by `QJ_BLESS=1 cargo test --release --test jq_compile disasm_vs_live_jq -- --ignored`."
        )
        .unwrap();
        for r in &records {
            writeln!(f, "{}", serde_json::to_string(r).unwrap()).unwrap();
        }
        eprintln!("wrote {}", path.display());
    }
    assert!(fails.is_empty(), "{} programs differ from jq", fails.len());
}

