#[derive(Clone, Debug, PartialEq, Eq)]
struct Outcome {
    exit: i32,
    stdout: String,
    stderr: String,
}

/// `realpath(tests/jq_compat)`.
fn compat_root() -> PathBuf {
    let root = jq_realpath(Value::from(compat_dir().to_str().unwrap()));
    PathBuf::from(root.as_str().unwrap())
}

fn normalize(s: &str) -> String {
    s.replace(compat_root().to_str().unwrap(), "$ROOT")
}

/// What main.c passes to `jq_compile_args` for `p`'s arguments (without
/// `JQ_BUILD_CONFIGURATION`), and the attributes it sets.
fn options(p: &Program) -> CompileOptions {
    let mut named = Object::new();
    let mut i = 0;
    while i + 3 <= p.args.len() {
        let (opt, name, text) = (&p.args[i], &p.args[i + 1], &p.args[i + 2]);
        // First definition wins.
        if !named.contains_key(name) {
            let v = match opt.as_str() {
                "--arg" => Value::from(text.as_str()),
                "--argjson" => qj::jq::value::parse::parse(text).expect("--argjson value"),
                o => panic!("unsupported option {o}"),
            };
            named.insert(Str::from(name.as_str()), v);
        }
        i += 3;
    }
    let mut a = Object::new();
    let positional: Vec<Value> = p
        .positional
        .iter()
        .map(|s| Value::from(s.as_str()))
        .collect();
    a.insert(Str::from("positional"), Value::from(positional));
    a.insert(Str::from("named"), Value::Object(named.clone()));
    let mut args = named;
    args.insert(Str::from("ARGS"), Value::Object(a));
    let mut env = Object::new();
    let penv = p.env();
    for (k, v) in &penv {
        env.insert(Str::from(k.as_str()), Value::from(v.as_str()));
    }
    let modules = jq_realpath(Value::from(compat_dir().join("modules").to_str().unwrap()));
    CompileOptions {
        args,
        env: Some(Value::Object(env)),
        attrs: JqAttrs {
            // main.c realpaths each -L directory
            lib_dirs: Value::from(vec![modules]),
            jq_origin: Value::from(dirname(jq_binary().to_str().unwrap()).as_str()),
            prog_origin: jq_realpath(Value::from(compat_dir().to_str().unwrap())),
            home: Some(penv[0].1.clone()),
        },
    }
}

fn ours(p: &Program) -> Outcome {
    match jq_compile_args(&p.src, &options(p)) {
        Ok(bc) => Outcome {
            exit: 0,
            stdout: normalize(&format!("{}\n", dump_disassembly(0, &bc))),
            stderr: String::new(),
        },
        Err(e) => Outcome {
            exit: 3,
            stdout: String::new(),
            stderr: normalize(&e.render()),
        },
    }
}

/// jq's outcome, or `None` if it crashed or timed out.
fn live_jq(jq: &Path, p: &Program) -> Option<Outcome> {
    use std::os::unix::ffi::OsStrExt;
    let mut cmd = Command::new(jq);
    cmd.args(["--debug-dump-disasm", "-L", "modules"])
        .args(&p.args);
    if !p.positional.is_empty() {
        cmd.arg("--args");
    }
    cmd.arg("--")
        .arg(std::ffi::OsStr::from_bytes(&p.src))
        .args(&p.positional)
        .current_dir(compat_dir())
        .env_clear()
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped());
    for (k, v) in p.env() {
        cmd.env(k, v);
    }
    let child = cmd.spawn().ok()?;
    let out = wait_with_timeout(child, Duration::from_secs(60))?;
    let exit = out.status.code()?;
    Some(Outcome {
        exit,
        stdout: normalize(&String::from_utf8_lossy(&out.stdout)),
        stderr: normalize(&String::from_utf8_lossy(&out.stderr)),
    })
}

fn wait_with_timeout(child: std::process::Child, t: Duration) -> Option<std::process::Output> {
    let (tx, rx) = std::sync::mpsc::channel();
    let id = child.id();
    std::thread::spawn(move || {
        let _ = tx.send(child.wait_with_output());
    });
    match rx.recv_timeout(t) {
        Ok(r) => r.ok(),
        Err(_) => {
            // SAFETY: plain kill(2) of our own child.
            unsafe { libc::kill(id as i32, libc::SIGKILL) };
            None
        }
    }
}

