#[derive(Clone, Debug, PartialEq, Eq, Hash)]
struct Program {
    origin: String,
    /// Raw bytes: a few programs are not valid UTF-8.
    src: Vec<u8>,
    /// jq options before the program: `--arg NAME VALUE` / `--argjson NAME JSON`.
    args: Vec<String>,
    /// Positional arguments after the program (`--args`).
    positional: Vec<String>,
    /// `$HOME`, relative to `tests/jq_compat` (default: [`ENV`]'s).
    home: Option<String>,
    /// Generated by [`generated_programs`] (recorded by origin only).
    generated: bool,
}

impl Program {
    fn new(origin: String, src: Vec<u8>) -> Program {
        Program {
            origin,
            src,
            args: Vec::new(),
            positional: Vec::new(),
            home: None,
            generated: false,
        }
    }

    /// Identity within the recording.
    fn key(&self) -> (Vec<u8>, Vec<String>, Vec<String>, Option<String>) {
        (
            self.src.clone(),
            self.args.clone(),
            self.positional.clone(),
            self.home.clone(),
        )
    }

    /// The environment jq runs with.
    /// The environment jq runs with (`"home": "<unset>"` leaves `HOME` out).
    fn env(&self) -> Vec<(String, String)> {
        ENV.iter()
            .filter(|(k, _)| !(*k == "HOME" && self.home.as_deref() == Some("<unset>")))
            .map(|(k, v)| match (*k, &self.home) {
                ("HOME", Some(h)) => (k.to_string(), compat_root().join(h).display().to_string()),
                _ => (k.to_string(), v.to_string()),
            })
            .collect()
    }
}

fn hex(b: &[u8]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

fn unhex(s: &str) -> Vec<u8> {
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
        .collect()
}

fn show(src: &[u8], n: usize) -> String {
    String::from_utf8_lossy(src).chars().take(n).collect()
}

fn strings(v: Option<&serde_json::Value>) -> Vec<String> {
    v.and_then(|v| v.as_array())
        .map(|a| a.iter().map(|s| s.as_str().unwrap().to_string()).collect())
        .unwrap_or_default()
}

/// A program from a JSON line: a string, or `{src|src_hex, origin?, args?,
/// positional?}`. `None` for Track P's generated entries (no source).
fn json_program(v: &serde_json::Value, default_origin: String) -> Option<Program> {
    match v {
        serde_json::Value::String(s) => Some(Program::new(default_origin, s.as_bytes().to_vec())),
        serde_json::Value::Object(o) => {
            let src = match (o.get("src"), o.get("src_hex")) {
                (Some(serde_json::Value::String(s)), _) => s.as_bytes().to_vec(),
                (_, Some(serde_json::Value::String(h))) => unhex(h),
                _ => return None,
            };
            let mut p = Program::new(
                o.get("origin")
                    .and_then(|v| v.as_str())
                    .map_or(default_origin, str::to_string),
                src,
            );
            p.args = strings(o.get("args"));
            p.positional = strings(o.get("positional"));
            p.home = o.get("home").and_then(|v| v.as_str()).map(str::to_string);
            Some(p)
        }
        _ => None,
    }
}

fn skipline(line: &str) -> bool {
    let rest = line.trim_start_matches([' ', '\t']);
    rest.is_empty() || rest.starts_with('#')
}

/// The programs of a jq `.test` file (jq_test.c's format).
fn test_file_programs(name: &str, content: &str, out: &mut Vec<Program>) {
    let lines: Vec<&str> = content.split('\n').collect();
    let mut i = 0;
    let mut must_fail = false;
    while i < lines.len() {
        let line = lines[i];
        let lineno = i + 1;
        i += 1;
        if skipline(line) {
            continue;
        }
        if line == "%%FAIL" || line == "%%FAIL IGNORE MSG" {
            must_fail = true;
            continue;
        }
        let origin = format!("{name}:{lineno}{}", if must_fail { " %%FAIL" } else { "" });
        out.push(Program::new(origin, line.as_bytes().to_vec()));
        if !must_fail {
            i += 1; // the input line
        }
        while i < lines.len() && !skipline(lines[i]) {
            i += 1;
        }
        must_fail = false;
    }
}

fn jsonl_programs(path: &Path, out: &mut Vec<Program>) {
    let name = path.file_name().unwrap().to_string_lossy().to_string();
    let content = std::fs::read_to_string(path).unwrap();
    for (n, line) in content.lines().enumerate() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let v: serde_json::Value = serde_json::from_str(line)
            .unwrap_or_else(|e| panic!("{}:{}: {e}", path.display(), n + 1));
        if let Some(p) = json_program(&v, format!("{name}:{}", n + 1)) {
            out.push(p);
        }
    }
}

/// Deep and long programs, around jq's limits (bison's 10000-state stack, the
/// 65535-unit function length) and past the depths where recursion would overflow.
fn generated_programs() -> Vec<(String, Vec<u8>)> {
    let mut out: Vec<(String, String)> = Vec::new();
    // Track P's: jq folds these while parsing, so they compile at any length.
    out.push((
        "chain-plus[100000]".into(),
        format!("1{}", "+1".repeat(100_000)),
    ));
    out.push((
        "chain-comma[100000]".into(),
        format!("[1{}]", ",1".repeat(100_000)),
    ));
    for n in [3400usize, 5000] {
        let pairs: Vec<String> = (0..n).map(|i| format!("a{i}:1")).collect();
        out.push((
            format!("object-pairs[{n}]"),
            format!("{{{}}}", pairs.join(",")),
        ));
    }
    for n in [4999usize, 9996] {
        out.push((format!("deep-neg[{n}]"), "-".repeat(n) + "1"));
    }
    for n in [9998usize, 10001] {
        out.push((format!("deep[{n}]"), "[".repeat(n) + &"]".repeat(n)));
    }
    out.push((
        "deep-paren-plus[4999]".into(),
        "(1+".repeat(4999) + "1" + &")".repeat(4999),
    ));
    out.push((
        "deep-interp[3333]".into(),
        "\"\\(".repeat(3333) + &")\"".repeat(3333),
    ));
    // Non-constant arithmetic nests one lambda per operator.
    for n in [3000usize, 10923, 20000] {
        out.push((format!("dotplus[{n}]"), vec!["."; n].join(" + ")));
    }
    for n in [21844usize, 21845, 100_000] {
        out.push((format!("field[{n}]"), ".a".repeat(n)));
    }
    out.push((
        "deepcall[1000]".into(),
        "def f(g): g; ".to_string() + &"f(".repeat(1000) + "." + &")".repeat(1000),
    ));
    let defs: String = (0..1000).map(|i| format!("def f{i}: ")).collect();
    let uses: String = (0..1000).rev().map(|i| format!("; f{i}")).collect();
    out.push(("deepdef[1000]".into(), defs + "." + &uses));
    let chain: String = (1..4000)
        .map(|i| format!("def f{i}: f{}; ", i - 1))
        .collect();
    out.push(("manydefs[4000]".into(), format!("def f0: 1; {chain}f3999")));
    let vars: String = (0..1000).map(|i| format!("1 as $x{i} | ")).collect();
    out.push(("manyvars[1000]".into(), vars + "[$x0, $x999]"));
    out.push(("deeptry[4990]".into(), "try ".repeat(4990) + "1"));
    out.push((
        "deepcollect[3000]".into(),
        "[.[] | ".repeat(3000) + "." + &"]".repeat(3000),
    ));
    let flat: Vec<String> = (0..6554).map(|i| format!("(1 as $x{i} | $x{i})")).collect();
    out.push(("manyvarsflat[6554]".into(), format!("[{}]", flat.join(","))));
    // The deepest nesting jq's parser accepts, for each construct.
    out.push((
        "max:array[9995]".into(),
        "[".repeat(9995) + &"]".repeat(9995),
    ));
    out.push(("max:neg[9995]".into(), "-".repeat(9995) + "1"));
    out.push(("max:try[9995]".into(), "try ".repeat(9995) + "1"));
    out.push((
        "max:arraypattern[9992]".into(),
        ". as ".to_string() + &"[".repeat(9992) + "$x" + &"]".repeat(9992) + " | $x",
    ));
    let defs: String = (0..3331).map(|i| format!("def f{i}: ")).collect();
    let uses: String = (0..3331).rev().map(|i| format!("; f{i}")).collect();
    out.push(("max:def[3331]".into(), defs + "." + &uses));
    out.push((
        "max:collect[3331]".into(),
        "[.[] | ".repeat(3331) + "." + &"]".repeat(3331),
    ));
    out.push((
        "max:object[3331]".into(),
        "{a:".repeat(3331) + "1" + &"}".repeat(3331),
    ));
    out.push((
        "max:if[3330]".into(),
        "if . then ".repeat(3330) + "1" + &" else 2 end".repeat(3330),
    ));
    out.push((
        "max:reduce[1998]".into(),
        "reduce .[] as $x (".repeat(1998) + "0" + &"; .)".repeat(1998),
    ));
    // (Binding nested labels is quadratic in jq too: 3331 of them take jq a second.)
    let labels: String = (0..600).map(|i| format!("label $l{i} | ")).collect();
    out.push(("labels[600]".into(), labels + "break $l0"));
    let vars: String = (0..2498).map(|i| format!("1 as $x{i} | ")).collect();
    out.push(("max:vars[2498]".into(), vars + "$x0"));
    out.push((
        "max:paren-plus[3331]".into(),
        "(1+".repeat(3331) + "1" + &")".repeat(3331),
    ));
    out.push((
        "max:paren-dotplus[3331]".into(),
        "(.+".repeat(3331) + "." + &")".repeat(3331),
    ));
    out.into_iter()
        .map(|(n, s)| (format!("gen:{n}"), s.into_bytes()))
        .collect()
}

/// The programs at jq's nesting limits, plus the deepest nested call (whose
/// disassembly is too big to record: 75 MB).
fn deepest_programs() -> Vec<(String, Vec<u8>)> {
    let mut out: Vec<(String, Vec<u8>)> = generated_programs()
        .into_iter()
        .filter(|(n, _)| n.starts_with("gen:max:"))
        .collect();
    let call = "def f(g): g; ".to_string() + &"f(".repeat(4996) + "." + &")".repeat(4996);
    out.push(("gen:max:call[4996]".into(), call.into_bytes()));
    out
}

fn collect_programs() -> Vec<Program> {
    let mut all = Vec::new();
    for dir in [compat_dir(), compat_dir().join("corpus")] {
        let mut files: Vec<PathBuf> = std::fs::read_dir(&dir)
            .unwrap()
            .map(|e| e.unwrap().path())
            .filter(|p| p.extension().is_some_and(|e| e == "test"))
            .collect();
        files.sort();
        for f in files {
            let name = f.strip_prefix(compat_dir()).unwrap().display().to_string();
            let content = std::fs::read_to_string(&f).unwrap();
            test_file_programs(&name, &content, &mut all);
        }
    }
    for f in ["corpus.jsonl", "cases.jsonl"] {
        jsonl_programs(&Path::new(ROOT).join("tests/jq_lang").join(f), &mut all);
    }
    jsonl_programs(&data_dir().join("corpus.jsonl"), &mut all);
    for (origin, src) in generated_programs() {
        let mut p = Program::new(origin, src);
        p.generated = true;
        all.push(p);
    }
    // Deduplicate; jq's CLI reads the program as a C string, so skip ones with NUL.
    let mut seen = HashSet::new();
    all.retain(|p| !p.src.contains(&0) && seen.insert(p.key()));
    all
}

